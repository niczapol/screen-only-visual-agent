"""Read-only inventory for large local dataset and debug directories.

The script walks selected roots, summarizes file counts, byte sizes, extension
groups, and largest files, then writes a Markdown report. It never deletes,
moves, renames, compresses, or edits dataset files.
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Iterable


DEFAULT_ROOTS = ("data", "debug_output", "runs")


@dataclass(frozen=True)
class FileInfo:
    path: Path
    size: int
    suffix: str
    mtime: float


@dataclass
class DirSummary:
    path: Path
    files: int = 0
    size: int = 0
    latest_mtime: float = 0.0


def format_size(num_bytes: int) -> str:
    units = ("B", "KB", "MB", "GB", "TB")
    value = float(num_bytes)
    for unit in units:
        if value < 1024.0 or unit == units[-1]:
            if unit == "B":
                return f"{int(value)} {unit}"
            return f"{value:.3f} {unit}"
        value /= 1024.0
    return f"{value:.3f} TB"


def iter_files(root: Path) -> Iterable[FileInfo]:
    stack = [root]
    while stack:
        current = stack.pop()
        try:
            entries = list(current.iterdir())
        except OSError:
            continue
        for entry in entries:
            try:
                if entry.is_symlink():
                    continue
                if entry.is_dir():
                    stack.append(entry)
                    continue
                if entry.is_file():
                    stat = entry.stat()
                    yield FileInfo(
                        path=entry,
                        size=stat.st_size,
                        suffix=entry.suffix.lower() or "<none>",
                        mtime=stat.st_mtime,
                    )
            except OSError:
                continue


def first_level_child(root: Path, file_path: Path) -> Path:
    try:
        relative = file_path.relative_to(root)
    except ValueError:
        return root
    if not relative.parts:
        return root
    return root / relative.parts[0]


def inventory_roots(roots: list[Path]) -> tuple[list[DirSummary], dict[str, DirSummary], dict[str, DirSummary], list[FileInfo]]:
    root_summaries: dict[str, DirSummary] = {}
    child_summaries: dict[str, DirSummary] = {}
    extension_summaries: dict[str, DirSummary] = defaultdict(lambda: DirSummary(path=Path()))
    all_files: list[FileInfo] = []

    for root in roots:
        if not root.exists():
            continue
        root_summary = DirSummary(path=root)
        root_summaries[str(root)] = root_summary
        for info in iter_files(root):
            all_files.append(info)

            root_summary.files += 1
            root_summary.size += info.size
            root_summary.latest_mtime = max(root_summary.latest_mtime, info.mtime)

            child = first_level_child(root, info.path)
            child_key = str(child)
            child_summary = child_summaries.setdefault(child_key, DirSummary(path=child))
            child_summary.files += 1
            child_summary.size += info.size
            child_summary.latest_mtime = max(child_summary.latest_mtime, info.mtime)

            ext_summary = extension_summaries[info.suffix]
            ext_summary.path = Path(info.suffix)
            ext_summary.files += 1
            ext_summary.size += info.size
            ext_summary.latest_mtime = max(ext_summary.latest_mtime, info.mtime)

    return list(root_summaries.values()), child_summaries, extension_summaries, all_files


def format_mtime(timestamp: float) -> str:
    if not timestamp:
        return "-"
    return datetime.fromtimestamp(timestamp).strftime("%Y-%m-%d %H:%M:%S")


def markdown_table(headers: tuple[str, ...], rows: list[tuple[str, ...]]) -> list[str]:
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(row) + " |")
    return lines


def build_report(
    roots: list[Path],
    root_summaries: list[DirSummary],
    child_summaries: dict[str, DirSummary],
    extension_summaries: dict[str, DirSummary],
    all_files: list[FileInfo],
    top: int,
) -> str:
    total_size = sum(item.size for item in root_summaries)
    total_files = sum(item.files for item in root_summaries)
    generated = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    lines: list[str] = [
        "# Dataset Inventory Report",
        "",
        f"Generated: {generated}",
        "",
        "This report is generated by a read-only inventory script. Dataset files",
        "were not deleted, moved, renamed, compressed, or edited.",
        "",
        f"Roots scanned: {', '.join(str(root) for root in roots)}",
        f"Total files: {total_files}",
        f"Total size: {format_size(total_size)}",
        "",
        "## Root Totals",
        "",
    ]

    root_rows = [
        (
            str(item.path),
            str(item.files),
            format_size(item.size),
            format_mtime(item.latest_mtime),
        )
        for item in sorted(root_summaries, key=lambda item: item.size, reverse=True)
    ]
    lines.extend(markdown_table(("Path", "Files", "Size", "Latest Write"), root_rows))

    lines.extend(["", "## Largest First-Level Directories", ""])
    child_rows = [
        (
            str(item.path),
            str(item.files),
            format_size(item.size),
            format_mtime(item.latest_mtime),
        )
        for item in sorted(child_summaries.values(), key=lambda item: item.size, reverse=True)[:top]
    ]
    lines.extend(markdown_table(("Path", "Files", "Size", "Latest Write"), child_rows))

    lines.extend(["", "## Extension Totals", ""])
    ext_rows = [
        (str(item.path), str(item.files), format_size(item.size))
        for item in sorted(extension_summaries.values(), key=lambda item: item.size, reverse=True)
    ]
    lines.extend(markdown_table(("Extension", "Files", "Size"), ext_rows))

    lines.extend(["", "## Largest Files", ""])
    file_rows = [
        (
            str(info.path),
            format_size(info.size),
            format_mtime(info.mtime),
        )
        for info in sorted(all_files, key=lambda item: item.size, reverse=True)[:top]
    ]
    lines.extend(markdown_table(("Path", "Size", "Latest Write"), file_rows))
    lines.append("")
    return "\n".join(lines)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--roots",
        nargs="+",
        default=list(DEFAULT_ROOTS),
        help="Roots to scan. Defaults to data debug_output runs.",
    )
    parser.add_argument(
        "--output",
        default="debug_output/dataset_inventory_report.md",
        help="Markdown report path to write.",
    )
    parser.add_argument(
        "--top",
        type=int,
        default=40,
        help="Number of largest directories/files to include.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    roots = [Path(root) for root in args.roots]
    existing_roots = [root for root in roots if root.exists()]
    root_summaries, child_summaries, extension_summaries, all_files = inventory_roots(existing_roots)
    report = build_report(
        roots=existing_roots,
        root_summaries=root_summaries,
        child_summaries=child_summaries,
        extension_summaries=extension_summaries,
        all_files=all_files,
        top=max(args.top, 1),
    )

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(report, encoding="utf-8")
    print(f"Wrote {output_path}")
    print(f"Scanned {len(all_files)} files, {format_size(sum(item.size for item in all_files))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
