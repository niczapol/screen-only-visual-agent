"""Create a stricter trainable manifest from local navigation outcome labels.

The source outcome labels are useful but noisy. This cleaner preserves the
original dataset and writes a filtered copy for baseline ML experiments.
"""

from __future__ import annotations

import argparse
import json
import shutil
from collections import Counter
from pathlib import Path
from typing import Any

import cv2
import numpy as np


TRAINABLE_LABELS = {"blocked", "passable"}
RECOVERY_REASONS = {"recovery_action"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Clean local-navigation outcome metadata.")
    parser.add_argument(
        "--input",
        default="data/local_navigation_outcome_dataset_v0_2/metadata.jsonl",
        help="Input metadata.jsonl generated by the route-probe outcome dataset builder.",
    )
    parser.add_argument(
        "--output-dir",
        default="data/local_navigation_outcome_dataset_v0_2_clean",
        help="Output directory for cleaned metadata and audit manifests.",
    )
    parser.add_argument("--min-coord-delta", type=float, default=0.015)
    parser.add_argument("--min-distance-progress", type=float, default=0.025)
    parser.add_argument("--max-coord-delta", type=float, default=2.0)
    parser.add_argument("--max-passable-obstacle-score", type=float, default=0.56)
    parser.add_argument("--min-blocked-obstacle-score", type=float, default=0.08)
    parser.add_argument("--contact-sheet-limit", type=int, default=48)
    return parser.parse_args()


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    with path.open("r", encoding="utf-8") as file:
        return [json.loads(line) for line in file if line.strip()]


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    with path.open("w", encoding="utf-8") as file:
        for row in rows:
            file.write(json.dumps(row, ensure_ascii=False) + "\n")


def attempted_sector(row: dict[str, Any]) -> dict[str, Any] | None:
    name = row.get("attempted_sector")
    navigation = row.get("navigation") if isinstance(row.get("navigation"), dict) else {}
    for sector in navigation.get("sectors") or []:
        if sector.get("name") == name:
            return sector
    return None


def has_forward_evidence(row: dict[str, Any], min_coord_delta: float, min_distance_progress: float) -> bool:
    coord_delta = row.get("coord_delta")
    distance_progress = row.get("distance_progress")
    coord_ok = isinstance(coord_delta, (int, float)) and coord_delta >= min_coord_delta
    distance_ok = isinstance(distance_progress, (int, float)) and distance_progress >= min_distance_progress
    return coord_ok or distance_ok


def add_audit(row: dict[str, Any], decision: str, reason: str) -> dict[str, Any]:
    output = dict(row)
    output["cleaning"] = {"decision": decision, "reason": reason}
    return output


def classify_row(row: dict[str, Any], args: argparse.Namespace) -> tuple[str, str]:
    label = row.get("label")
    reason = row.get("reason")
    sector = attempted_sector(row)
    if label not in {"blocked", "passable", "unknown"}:
        return "exclude", "bad_label"
    if row.get("source_frame") is None:
        return "exclude", "missing_source_frame"
    if sector is None:
        return "exclude", "missing_attempted_sector"
    if label == "unknown":
        return "exclude", "unknown_not_ground_truth"

    coord_delta = row.get("coord_delta")
    if isinstance(coord_delta, (int, float)) and coord_delta > args.max_coord_delta:
        return "review", "coord_delta_outlier"

    obstacle_score = float(sector.get("obstacle_score", 0.0) or 0.0)
    visual_stuck_samples = int(row.get("visual_stuck_samples") or 0)
    movement = row.get("movement") if isinstance(row.get("movement"), dict) else {}
    movement_action = str(movement.get("action") or "")
    action = str(row.get("action") or "")

    if label == "passable":
        if reason != "coordinate_progress":
            return "review", "passable_without_coordinate_progress_reason"
        if action == "reached":
            return "review", "reached_is_not_continuous_movement"
        if visual_stuck_samples > 0:
            return "review", "passable_with_visual_stuck_samples"
        if not has_forward_evidence(row, args.min_coord_delta, args.min_distance_progress):
            return "review", "passable_without_forward_evidence"
        if obstacle_score >= args.max_passable_obstacle_score:
            return "review", "passable_high_obstacle_score"
        return "keep", "strict_passable_progress"

    if label == "blocked":
        if reason in RECOVERY_REASONS:
            return "review", "recovery_action_temporal_shift"
        if visual_stuck_samples >= 2:
            return "keep", "strict_visual_stuck"
        if reason == "fresh_no_progress_low_visual_motion":
            return "keep", "strict_no_progress_low_motion"
        if movement_action.startswith("recover_") or action.startswith("recover_"):
            return "review", "recovery_action_temporal_shift"
        if obstacle_score >= args.min_blocked_obstacle_score and not has_forward_evidence(
            row,
            args.min_coord_delta,
            args.min_distance_progress,
        ):
            return "review", "possible_blocked_needs_visual_review"
        return "review", "blocked_without_strict_evidence"

    return "exclude", "unhandled_label"


def copy_episode_splits(input_path: Path, output_dir: Path) -> None:
    splits_path = input_path.parent / "episode_splits.json"
    if splits_path.exists():
        shutil.copy2(splits_path, output_dir / "episode_splits.original.json")


def make_contact_sheet(rows: list[dict[str, Any]], output_path: Path, limit: int) -> None:
    selected = rows[: max(0, limit)]
    if not selected:
        return

    tiles: list[np.ndarray] = []
    for row in selected:
        image_path = Path(str(row.get("source_frame")))
        image = cv2.imread(str(image_path), cv2.IMREAD_COLOR)
        if image is None:
            continue
        height, width = image.shape[:2]
        tile = cv2.resize(image, (512, 288), interpolation=cv2.INTER_AREA)
        sector = attempted_sector(row)
        if sector:
            bbox = sector.get("bbox") or {}
            x1 = int(float(bbox.get("x", 0)) * 512 / width)
            y1 = int(float(bbox.get("y", 0)) * 288 / height)
            x2 = int(float(bbox.get("x", 0) + bbox.get("width", 0)) * 512 / width)
            y2 = int(float(bbox.get("y", 0) + bbox.get("height", 0)) * 288 / height)
            color = (40, 40, 230) if row.get("label") == "blocked" else (40, 190, 40)
            cv2.rectangle(tile, (x1, y1), (x2, y2), color, 2)
        cleaning = row.get("cleaning") or {}
        title = f"{row.get('split')} {row.get('label')} {cleaning.get('reason') or row.get('reason')}"
        cv2.rectangle(tile, (0, 0), (512, 28), (0, 0, 0), -1)
        cv2.putText(tile, title[:78], (8, 20), cv2.FONT_HERSHEY_SIMPLEX, 0.47, (235, 235, 235), 1, cv2.LINE_AA)
        tiles.append(tile)

    if not tiles:
        return
    cols = 3
    rows_count = (len(tiles) + cols - 1) // cols
    blank = np.zeros_like(tiles[0])
    while len(tiles) < rows_count * cols:
        tiles.append(blank.copy())
    grid_rows = [np.hstack(tiles[index : index + cols]) for index in range(0, len(tiles), cols)]
    cv2.imwrite(str(output_path), np.vstack(grid_rows))


def main() -> None:
    args = parse_args()
    input_path = Path(args.input)
    if not input_path.is_absolute():
        input_path = Path.cwd() / input_path
    input_path = input_path.resolve()
    output_dir = Path(args.output_dir)
    if not output_dir.is_absolute():
        output_dir = Path.cwd() / output_dir
    output_dir.mkdir(parents=True, exist_ok=True)

    kept: list[dict[str, Any]] = []
    review: list[dict[str, Any]] = []
    excluded: list[dict[str, Any]] = []

    for row in read_jsonl(input_path):
        decision, reason = classify_row(row, args)
        audited = add_audit(row, decision, reason)
        if decision == "keep":
            kept.append(audited)
        elif decision == "review":
            review.append(audited)
        else:
            excluded.append(audited)

    write_jsonl(output_dir / "metadata.jsonl", kept)
    write_jsonl(output_dir / "review_candidates.jsonl", review)
    write_jsonl(output_dir / "excluded.jsonl", excluded)
    copy_episode_splits(input_path, output_dir)

    summary = {
        "input": str(input_path),
        "output_dir": str(output_dir),
        "total_rows": len(kept) + len(review) + len(excluded),
        "kept_rows": len(kept),
        "review_rows": len(review),
        "excluded_rows": len(excluded),
        "kept_label_counts": dict(Counter(row.get("label") for row in kept)),
        "kept_split_counts": dict(Counter(row.get("split") for row in kept)),
        "review_reason_counts": dict(Counter((row.get("cleaning") or {}).get("reason") for row in review)),
        "excluded_reason_counts": dict(Counter((row.get("cleaning") or {}).get("reason") for row in excluded)),
        "rules": {
            "unknown": "excluded from trainable metadata, because it is not ground truth",
            "recovery_action": "review-only by default, because the frame can be temporally shifted",
            "passable": "requires coordinate_progress, continuous movement, no stuck samples, non-outlier coordinate delta",
            "blocked": "requires visual_stuck_samples >= 2 or fresh no-progress low-motion evidence",
        },
    }
    (output_dir / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")
    make_contact_sheet(kept, output_dir / "kept_contact_sheet.png", args.contact_sheet_limit)
    make_contact_sheet(review, output_dir / "review_contact_sheet.png", args.contact_sheet_limit)
    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
